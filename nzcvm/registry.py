"""Global object registry for dask-safe handling of unpicklable Rust-backed objects.

With the dask ``distributed`` scheduler running ``processes=False`` (thread
workers only), all workers share the same Python process.  This module exposes:

* :data:`REGISTRY` -- a global ``{uuid → object}`` dictionary.  Every key is a
  UUID string.

* :func:`pickle_pass` -- stores an object in :data:`REGISTRY` under a fresh
  UUID and returns only the UUID.  Classes holding an unpicklable Rust-backed
  attribute (:class:`~nzcvm.models.model.ModelTree` and
  :class:`~nzcvm.layers.coastline.CoastlineLayer`) override
  ``__getstate__`` to replace that attribute with ``pickle_pass(attr)``, and
  ``__setstate__`` to swap the UUID back for ``REGISTRY[uuid]``.  The lookup
  only succeeds when pickling and unpickling happen in the same process, as
  under ``processes=False``, and it doesn't copy any data.

* :func:`pipeline_context` -- a :mod:`contextlib` context manager that clears
  :data:`REGISTRY` after the pipeline (including any lazy dask ``.compute()``
  calls) finishes, releasing all cached objects.

Pipeline layers must load their resources (models, surfaces, …) *outside* any
``map_blocks`` / ``apply_ufunc`` boundary, then pass the loaded objects as
explicit kwargs so that dask can serialise them via :func:`pickle_pass`.
"""

import contextlib
import logging
import uuid
from typing import Any

logger = logging.getLogger(__name__)

#: Global pool mapping UUID strings to Python objects.
#:
#: Keys are UUID strings generated by :func:`pickle_pass` when an object is
#: pickled.  :func:`pipeline_context` empties the pool as it exits.
REGISTRY: dict[str, Any] = {}


def pickle_pass(obj: Any) -> str:
    """Store *obj* in :data:`REGISTRY` and return its key.

    Call this from ``__getstate__`` in place of pickling *obj*, and look the
    key up in :data:`REGISTRY` from ``__setstate__``.  This only works when
    the same process unpickles the object.

    Parameters
    ----------
    obj :
        Object to store.

    Returns
    -------
    str
        UUID key of *obj* in :data:`REGISTRY`.
    """
    obj_id = uuid.uuid4().hex
    REGISTRY[obj_id] = obj
    return obj_id


@contextlib.contextmanager
def pipeline_context():
    """Context manager that clears the object registry after the pipeline finishes.

    Wrap the pipeline execution *including any lazy* ``.compute()`` *calls*
    with this context, so that leaving the block releases every object
    :data:`REGISTRY` still caches.

    Yields
    ------
    None
        Control returns to the ``with`` block.

    Examples
    --------
    >>> with pipeline_context():  # doctest: +SKIP
    ...     vm_result = execute_model_pipeline(velocity_model, pipeline)
    ...     formats.write_velocity_model(vm_result, output)
    """
    try:
        yield
    finally:
        n = len(REGISTRY)
        REGISTRY.clear()
        logger.debug("Object registry cleared (%d entries removed).", n)
